#!/bin/sh
# Parity mechanics for the end-to-end suite.
#
# The same vocabulary as tests/conformance/harness.sh: `identical`, or
# `divergent in <field>` naming the field that first differs. The host
# recording and the in-sandbox plane run both record through the same
# test-support client wrapper, so the operation transcripts are comparable
# once the closed normalization set is applied.
#
# Normalization is additive to tests/conformance/normalize.sh and stays narrow:
# the two gateway names, this case's sandbox names, and the in-sandbox workdir
# path (protected from the repository rule, never rewritten). Nothing else is
# replaced; a changed operation, target, or field still differs.
#
# Usage (sourced):  . tests/e2e/parity.sh
# Usage (command):  parity.sh compare CASE RECORDED RUN
#                   parity.sh --self-test
set -u

E2E_PARITY_ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd -P)
. "$E2E_PARITY_ROOT/tests/conformance/normalize.sh"

# The gateway name is the only incidental target: each side names its own.
# Applied to `target=` lines only, never to a command or a path.
e2e_normalize_gateway() {
    sed -E 's/^target=(openshell|insandbox)$/target=<gateway>/'
}

# The sandbox workdir the cases are driven with. It is a path inside the
# sandbox, not the host checkout, so host recordings keep it literal.
E2E_SANDBOX_WORKDIR=/sandbox/project

# Protect that path when the suite itself runs from it: otherwise
# conformance_normalize's <repo> rule rewrites the sandbox workdir too. Only
# the standalone path is protected, never a repo sub-path such as
# /sandbox/project/examples/..., which must still normalize to <repo>.
e2e_protect_sandbox_workdir() {
    sed -E "s#${E2E_SANDBOX_WORKDIR}([[:space:]]|\$)#__e2e_sandbox_workdir__\1#g"
}

e2e_restore_sandbox_workdir() {
    sed "s#__e2e_sandbox_workdir__#${E2E_SANDBOX_WORKDIR}#g"
}

# Replace this case's sandbox names. The caller exports E2E_SANDBOXES as a
# space-separated list; names are generated by the harness, so they contain no
# sed-special characters. This runs before conformance_normalize: a generated
# name can carry 7+ hex characters, which the <commit> rule would otherwise
# rewrite before the name rule could match.
e2e_normalize_sandboxes() {
    [ -n "${E2E_SANDBOXES:-}" ] || {
        cat
        return 0
    }
    set --
    for e2e_name in ${E2E_SANDBOXES:-}; do
        set -- "$@" -e "s/$e2e_name/<sandbox>/g"
    done
    sed "$@"
}

# Local mode runs each exec child directly under the plane's per-sandbox root;
# the child sees that real directory as its `/sandbox`. Strip the root before
# any other rule so the child's own record of its workdir reads as the path the
# host recording names. Host mode has no such root and passes through.
e2e_strip_plane_root() {
    if [ -n "${PLANE_STATE:-}" ]; then
        sed -E "s#${PLANE_STATE}/sandboxes/[^/]+/root##g"
    else
        cat
    fi
}

# e2e_normalize CASE WORK REPO < in > out
e2e_normalize() {
    e2e_strip_plane_root \
        | e2e_normalize_sandboxes \
        | e2e_protect_sandbox_workdir \
        | conformance_normalize "$1" "$2" "$3" \
        | e2e_restore_sandbox_workdir \
        | e2e_normalize_gateway
}

# The first differing line's field name. The recorder's blocks are
# `op=`, `target=`, then `field=value` lines; any other shape is `recording`.
e2e_first_difference() { # RECORDED RUN
    e2e_line=$(awk 'FNR == NR { recorded[FNR] = $0; next }
        $0 != recorded[FNR] { print recorded[FNR]; exit }' "$1" "$2")
    case $e2e_line in
        op=*) printf '%s\n' operation ;;
        target=*) printf '%s\n' target ;;
        *=*) printf '%s\n' "${e2e_line%%=*}" ;;
        *) printf '%s\n' recording ;;
    esac
}

# e2e_verdict RECORDED RUN -> "identical" or "divergent in FIELD".
e2e_verdict() { # RECORDED RUN
    if [ ! -f "$2" ]; then
        printf '%s\n' "divergent in recording"
        return 0
    fi
    if cmp -s "$1" "$2"; then
        printf '%s\n' identical
        return 0
    fi
    printf 'divergent in %s\n' "$(e2e_first_difference "$1" "$2")"
}

# Command mode.
if [ "${0##*/}" = parity.sh ] && [ "${1:-}" != "" ]; then
    case $1 in
        compare)
            [ "$#" -ge 4 ] || {
                printf 'usage: %s compare CASE RECORDED RUN\n' "$0" >&2
                exit 2
            }
            verdict=$(e2e_verdict "$3" "$4")
            printf '%s (%s)\n' "$verdict" "$2"
            [ "$verdict" = identical ]
            exit
            ;;
        --self-test)
            work=$(mktemp -d "${TMPDIR:-/tmp}/e2e-parity.XXXXXX") || exit 2
            mkdir -p "$work/recorded" "$work/run"
            cat >"$work/recorded/operations.log" <<'EOF'
op=create_sandbox
target=<sandbox>
image=osa-dev:local
providers=e2e-noop
EOF
            cp "$work/recorded/operations.log" "$work/run/operations.log"
            status=0
            first=$(e2e_verdict "$work/recorded/operations.log" "$work/run/operations.log")
            [ "$first" = identical ] || {
                printf 'parity self-test: identical run reported %s\n' "$first" >&2
                status=1
            }
            sed 's/^providers=e2e-noop$/providers=other/' \
                "$work/recorded/operations.log" >"$work/run/operations.log"
            second=$(e2e_verdict "$work/recorded/operations.log" "$work/run/operations.log")
            [ "$second" = "divergent in providers" ] || {
                printf 'parity self-test: altered field reported %s\n' "$second" >&2
                status=1
            }

            # A generated sandbox name may carry 7+ hex characters. The name
            # rule must run before the <commit> rule, or the target diverges.
            cat >"$work/recorded/name.log" <<'EOF'
op=get_sandbox
target=<sandbox>
EOF
            printf 'op=get_sandbox\ntarget=e2e-01-abcdef1\n' >"$work/run/name.log"
            E2E_SANDBOXES=e2e-01-abcdef1 \
                e2e_normalize "$work/case" "$work" "$work/repo" \
                <"$work/run/name.log" >"$work/run/name.normalized.log"
            third=$(e2e_verdict "$work/recorded/name.log" "$work/run/name.normalized.log")
            [ "$third" = identical ] || {
                printf 'parity self-test: hex sandbox name reported %s\n' "$third" >&2
                status=1
            }

            # When the suite's own checkout is /sandbox/project, the repo rule
            # must not rewrite the in-sandbox workdir; a repo sub-path still
            # becomes <repo>.
            cat >"$work/recorded/paths.log" <<'EOF'
op=create_sandbox
policy=<repo>/examples/policies/maki-minimal.yaml
workdir=/sandbox/project
EOF
            printf 'op=create_sandbox\npolicy=/sandbox/project/examples/policies/maki-minimal.yaml\nworkdir=/sandbox/project\n' \
                >"$work/run/paths.log"
            E2E_SANDBOXES='' \
                e2e_normalize "$work/case" "$work" /sandbox/project \
                <"$work/run/paths.log" >"$work/run/paths.normalized.log"
            fourth=$(e2e_verdict "$work/recorded/paths.log" "$work/run/paths.normalized.log")
            [ "$fourth" = identical ] || {
                printf 'parity self-test: sandbox workdir reported %s\n' "$fourth" >&2
                status=1
            }

            if [ "$status" -eq 0 ]; then
                printf '%s\n' \
                    'parity self-test: identical, divergent in providers, hex sandbox name, sandbox workdir'
            fi
            rm -rf "$work"
            exit "$status"
            ;;
        *)
            printf 'usage: %s compare CASE RECORDED RUN\n' "$0" >&2
            exit 2
            ;;
    esac
fi
