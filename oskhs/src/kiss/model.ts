// Project model and credentials (B1.3d, design in add-oskhs-model-credentials).
// From a task's kiss `modelProvider`, oskhs derives a rule-restricted OpenShell
// profile per provider protocol and base URL, a provider instance per project
// that holds the key (passed by environment name only, never in argv), the
// sandbox's single attached provider, and Maki's custom provider config. The
// key never reaches the sandbox: Maki sees the gateway's stand-in.
import { createHash } from "node:crypto";
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { tail } from "../exec.ts";
import type { Ctx } from "../openshell.ts";

export interface KissModelProvider {
  id?: string;
  providerType?: string | null;
  baseUrl?: string | null;
  apiKey?: string | null;
  isExternal?: boolean | null;
}

export const CREDENTIAL_ENV = "OSKHS_MODEL_API_KEY";
export const MAKI_SLUG = "kiss";
export const MAKI_BINARY = "/usr/local/bin/maki";

export type Protocol = "openai" | "anthropic";

export interface ModelPlan {
  protocol: Protocol;
  profileId: string;
  providerName: string;
  host: string;
  port: number;
  baseUrl: string; // origin + path, no trailing slash
  rules: { method: string; path: string }[];
  modelSpec: string; // kiss/<id>
  fingerprint: string;
  profileYaml: string;
  makiConfig: string;
}

export class ModelError extends Error {}

const slug = (s: string, max = 30) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, max)
    .replace(/-$/, "");

const sha = (s: string) => createHash("sha256").update(s).digest("hex");

/** Derives everything oskhs needs from a kiss model provider; pure. */
export function planModel(mp: KissModelProvider | null | undefined, project: string): ModelPlan {
  if (!mp?.id) throw new ModelError("the task has no model provider (modelProvider.id)");
  if (!mp.apiKey) throw new ModelError(`model provider '${mp.id}' has no API key`);
  if (!mp.baseUrl) throw new ModelError(`model provider '${mp.id}' has no baseUrl`);
  const type = mp.providerType ?? "openai";
  if (type !== "openai" && type !== "anthropic") throw new ModelError(`model provider type '${type}' is not supported by oskhs`);
  let url: URL;
  try {
    url = new URL(mp.baseUrl);
  } catch {
    throw new ModelError(`model provider '${mp.id}' has an invalid baseUrl`);
  }
  if (url.protocol !== "https:") throw new ModelError(`model provider '${mp.id}' must use https (got ${url.protocol})`);
  const basePath = url.pathname.replace(/\/+$/, "");
  const baseUrl = `${url.origin}${basePath}`;
  const port = url.port ? Number(url.port) : 443;
  const rules =
    type === "openai"
      ? [{ method: "POST", path: `${basePath}/chat/completions` }, { method: "GET", path: `${basePath}/models` }]
      : [{ method: "POST", path: `${basePath}/v1/messages` }, { method: "GET", path: `${basePath}/v1/models` }];
  const profileId = `oskhs-${type}-${slug(url.hostname)}-${sha(baseUrl).slice(0, 6)}`;
  const providerName = `oskhs-${slug(project, 40)}`;
  const auth = type === "openai" ? { style: "bearer", header: "authorization" } : { style: "header", header: "x-api-key" };
  const profileYaml = [
    `# Generated by oskhs from a kiss model provider; inference paths only.`,
    `id: ${profileId}`,
    `display_name: oskhs ${type} ${url.hostname}`,
    `description: kiss model provider at ${baseUrl} (generated by oskhs)`,
    `category: inference`,
    `inference_capable: true`,
    `credentials:`,
    `  - name: api_key`,
    `    description: model API key from kiss`,
    `    env_vars: [${CREDENTIAL_ENV}]`,
    `    required: true`,
    `    auth_style: ${auth.style}`,
    `    header_name: ${auth.header}`,
    `discovery:`,
    `  credentials: [api_key]`,
    `endpoints:`,
    `  - host: ${url.hostname}`,
    `    port: ${port}`,
    `    protocol: rest`,
    `    enforcement: enforce`,
    `    rules:`,
    ...rules.map((r) => `      - allow: { method: ${r.method}, path: ${JSON.stringify(r.path)} }`),
    `binaries:`,
    `  - ${MAKI_BINARY}`,
    ``,
  ].join("\n");
  const makiConfig = [
    `# Written by oskhs for this round; holds no credential, only its variable name.`,
    `[${MAKI_SLUG}]`,
    `display_name = "kiss model (oskhs)"`,
    `protocol = "${type}"`,
    `base_url = ${JSON.stringify(baseUrl)}`,
    `api_key_env = "${CREDENTIAL_ENV}"`,
    ``,
    `[[${MAKI_SLUG}.models]]`,
    `id = ${JSON.stringify(mp.id)}`,
    `tier = "strong"`,
    `context_window = 128000`,
    `max_output_tokens = 16384`,
    ``,
  ].join("\n");
  return {
    protocol: type,
    profileId,
    providerName,
    host: url.hostname,
    port,
    baseUrl,
    rules,
    modelSpec: `${MAKI_SLUG}/${mp.id}`,
    fingerprint: sha(`${profileId}\n${mp.apiKey}`).slice(0, 16),
    profileYaml,
    makiConfig,
  };
}

interface ProviderState {
  [provider: string]: { type: string; fingerprint: string };
}

function readState(file: string): ProviderState {
  try {
    return JSON.parse(readFileSync(file, "utf8")) as ProviderState;
  } catch {
    return {};
  }
}

function writeState(file: string, state: ProviderState): void {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(state, null, 1) + "\n", { mode: 0o600 });
  chmodSync(file, 0o600);
}

const gw = (ctx: Ctx) => (ctx.gateway ? [ctx.openshell, "-g", ctx.gateway] : [ctx.openshell]);

async function must(ctx: Ctx, argv: string[], what: string, env?: Record<string, string>) {
  const out = await ctx.run(argv, env ? { env } : {});
  if (out.code !== 0) throw new ModelError(`${what} failed (exit ${out.code}): ${tail(out.stderr + out.stdout, 5)}`);
  return out;
}

/** Profile imported, provider created/updated to the current key. Before the sandbox exists. */
export async function ensureModelProvider(ctx: Ctx, plan: ModelPlan, apiKey: string, stateFile: string): Promise<void> {
  if ((await ctx.run([...gw(ctx), "profile", "describe", plan.profileId])).code !== 0) {
    const dir = await mkdtemp(join(tmpdir(), "oskhs-profile-"));
    try {
      const file = join(dir, `${plan.profileId}.yaml`);
      writeFileSync(file, plan.profileYaml);
      await must(ctx, [...gw(ctx), "profile", "import", "-f", file], `importing profile ${plan.profileId}`);
      ctx.log(`imported profile ${plan.profileId}`);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }
  const state = readState(stateFile);
  const known = state[plan.providerName];
  const exists = (await ctx.run([...gw(ctx), "provider", "get", plan.providerName])).code === 0;
  const env = { [CREDENTIAL_ENV]: apiKey }; // the value travels by environment only
  if (exists && known?.type === plan.profileId && known.fingerprint === plan.fingerprint) return;
  if (exists && known?.type === plan.profileId) {
    await must(ctx, [...gw(ctx), "provider", "update", plan.providerName, "--credential", CREDENTIAL_ENV], `updating provider ${plan.providerName}`, env);
    ctx.log(`updated provider ${plan.providerName}`);
  } else {
    if (exists) {
      // the type (profile) changed, or oskhs has no record of it: start over
      await detachEverywhere(ctx, plan.providerName);
      await must(ctx, [...gw(ctx), "provider", "delete", plan.providerName], `deleting provider ${plan.providerName}`);
    }
    await must(
      ctx,
      [...gw(ctx), "provider", "create", "--name", plan.providerName, "--type", plan.profileId, "--credential", CREDENTIAL_ENV],
      `creating provider ${plan.providerName}`,
      env,
    );
    ctx.log(`created provider ${plan.providerName} (${plan.profileId})`);
  }
  writeState(stateFile, { ...state, [plan.providerName]: { type: plan.profileId, fingerprint: plan.fingerprint } });
}

async function attached(ctx: Ctx, sandbox: string): Promise<string[]> {
  const out = await must(ctx, [...gw(ctx), "sandbox", "provider", "list", sandbox, "--output", "json"], `listing providers of ${sandbox}`);
  return ((JSON.parse(out.stdout || "{}").providers ?? []) as { name: string }[]).map((p) => p.name);
}

async function detachEverywhere(ctx: Ctx, provider: string): Promise<void> {
  const out = await ctx.run([...gw(ctx), "sandbox", "list", "--output", "json"]);
  const names = ((JSON.parse(out.stdout || "{}").sandboxes ?? []) as { name: string }[]).map((s) => s.name);
  for (const sandbox of names) {
    if ((await attached(ctx, sandbox)).includes(provider)) {
      await must(ctx, [...gw(ctx), "sandbox", "provider", "detach", sandbox, provider], `detaching ${provider} from ${sandbox}`);
    }
  }
}

/** The project's provider is the sandbox's only provider. After the sandbox exists. */
export async function pinSandboxProvider(ctx: Ctx, sandbox: string, provider: string): Promise<void> {
  const current = await attached(ctx, sandbox);
  for (const other of current.filter((p) => p !== provider)) {
    await must(ctx, [...gw(ctx), "sandbox", "provider", "detach", sandbox, other], `detaching ${other} from ${sandbox}`);
    ctx.log(`detached ${other} from ${sandbox}`);
  }
  if (!current.includes(provider)) {
    await must(ctx, [...gw(ctx), "sandbox", "provider", "attach", sandbox, provider, "--wait"], `attaching ${provider} to ${sandbox}`);
    ctx.log(`attached ${provider} to ${sandbox}`);
  }
}

export const providerStateFile = (stateDir: string) => join(stateDir, "providers.json");
